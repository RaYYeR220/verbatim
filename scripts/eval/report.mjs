// Renders results/SUMMARY.md from the JSON results, so no number is typed by hand.
//   node scripts/eval/report.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const read = (f) => JSON.parse(readFileSync(join(root, "results", f), "utf8"));
const pct = (x) => (x === null || x === undefined ? "—" : `${Math.round(x * 1000) / 10}%`);

const b8 = read("score-baseline-8.json");
const v8 = read("score-verbatim-8.json");
const b3 = read("score-baseline-3.json");
const v3 = read("score-verbatim-3.json");
const rb = read("reviews-baseline-500.score.json");
const rbRaw = read("reviews-baseline-500.json");
const rv = read("verbatim-reviews-500.json");

const quotedReviewers = new Set(rbRaw.themes.flatMap((t) => t.quotes.map((q) => (q.author ?? "").trim().toLowerCase()))).size;
const claimedCounts = rbRaw.themes.reduce((n, t) => n + (Number(t.reviewCount) || 0), 0);

const interviewRows = (b, v) => [
  ["Quotes cited", b.quotes, v.quotes],
  ["Quotes found verbatim in the transcripts", `${pct(b.quoteFidelity)} (${b.quotes - b.inventedQuotes}/${b.quotes})`, `${pct(v.quoteFidelity)} (${v.quotes - v.inventedQuotes}/${v.quotes})`],
  ["Quotes not in any transcript", b.inventedQuotes, v.inventedQuotes],
  ["Quotes credited to the wrong participant", b.misattributed, v.misattributed],
  ["Planted themes found", b.themeRecall, v.themeRecall],
  ["Single-participant (minority) theme found", b.minorityThemeFound ? "yes" : "no", v.minorityThemeFound ? "yes" : "no"],
  ["Both sides of the disagreement", b.contradictionSides, v.contradictionSides],
  ["Decoy themes (nobody said it)", b.decoyThemes, v.decoyThemes],
];

const table = (rows, a, b) =>
  [`| | ${a} | ${b} |`, "|---|---|---|", ...rows.map(([k, x, y]) => `| ${k} | ${x} | ${y} |`)].join("\n");

const md = `# Results

Generated by \`node scripts/eval/report.mjs\` from the JSON files in this folder. Same model for both columns (${rbRaw.model}).

## 500 public App Store reviews of Notion for iOS (real data, no answer key)

${table(
  [
    ["Reviews", rb.reviews, rv.sources],
    ["Reviews whose words appear in the synthesis", `${quotedReviewers} of ${rb.reviews}`, `${rv.sourcesOnBoard} of ${rv.sources}`],
    ["Quotes", rb.quotes, rv.notes],
    ["Quotes found verbatim in a review", `${pct(rb.quoteFidelity)}`, `${pct(rv.notesMatchingSource / rv.notes)} (checked on every write and every read)`],
    ["Quotes credited to the wrong reviewer", rb.creditedToWrongReviewer, "0 (speaker comes from the source, not the model)"],
    ["Themes", rb.themes, rv.themes],
    ["Theme counts you can open to the quotes behind them", `0 of ${rb.themes} (claimed counts add up to ${claimedCounts})`, `${rv.themesWithOpenableCounts} of ${rv.themes}`],
    ["Insights", "—", `${rv.insights} (${rv.verifiedInsights} verified on 2+ voices, ${rv.anecdotes} anecdotes)`],
    ["Quotes refused by the server", "—", `${rv.refused} (${Object.entries(rv.refusedByReason).map(([k, n]) => `${n} ${k.replace("_", " ")}`).join(", ")})`],
  ],
  "One chat prompt",
  "Verbatim",
)}

Refused quotes that were not in the source (the agent had quietly changed the customer's words):

${rv.refusedQuotes
  .filter((r) => r.reason === "not_found")
  .map((r) => `- \`${r.quote}\``)
  .join("\n")}

## 8 interviews (labelled synthetic benchmark with an answer key)

${table(interviewRows(b8, v8), "One chat prompt", "Verbatim")}

## 3 of those interviews

${table(interviewRows(b3, v3), "One chat prompt", "Verbatim")}

## Reading this honestly

- On clean, short interview sets the single prompt is as good at finding themes as Verbatim's agent. Verbatim does not claim better reading; it claims a result you can check and change.
- The single prompt's quotes were verbatim on the review corpus. Its gap there is coverage (most reviewers never appear) and counts nobody can open.
- Verbatim's agent did propose non-verbatim quotes; the server refused them before they reached the board.
`;

writeFileSync(join(root, "results", "SUMMARY.md"), md);
console.log(md);
